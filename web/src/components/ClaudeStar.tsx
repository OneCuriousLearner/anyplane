export function ClaudeStar(props: {
  /** 对话进行中：循环触手波 */
  active?: boolean
  className?: string
  size?: number
}) {
  const { active = false, className = '', size = 28 } = props
  const [pulse, setPulse] = useState(false)

  useEffect(() => {
    if (!pulse) return
    const t = window.setTimeout(() => setPulse(false), 600)
    return () => window.clearTimeout(t)
  }, [pulse])

  return (
    <button
      type="button"
      className={`claude-star inline-flex shrink-0 appearance-none border-0 bg-transparent p-0 ${
        active ? 'claude-star--active' : ''
      } ${pulse ? 'claude-star--pulse' : ''} ${active ? 'cursor-default' : 'cursor-pointer'} ${className}`}
      style={{ width: size, height: size }}
      disabled={active || pulse}
      aria-label={active ? 'Claude 工作中' : 'Claude'}
      title={active ? '工作中' : 'Hi there!'}
      onClick={() => {
        if (active || pulse) return
        setPulse(true)
      }}
    >
      <svg viewBox="0 0 125 125" width="100%" height="100%" aria-hidden="true">
        <path d={CORE_D} fill="#c15f3c" />
        {RAYS.map((d, i) => (
          <g
            key={i}
            className="claude-star__ray"
            style={{ ['--ray-index' as string]: i }}
          >
            <path d={d} fill="#c15f3c" />
          </g>
        ))}
      </svg>
    </button>
  )
}
